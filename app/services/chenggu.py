def compute(calendar: str, y: int, m: int, d: int, h: int) -> dict:
    """计算骨重。calendar=solar/lunar。返回 {total, parts, song, luck}。"""
    from . import lunisolar as L
    if calendar == "lunar":
        y_gz = y
        ly, lm, ld = y, m, d
    else:
        lunar = L.solar_to_lunar(y, m, d)
        ly, lm, ld = lunar["year"], lunar["month"], lunar["day"]
        y_gz = lunar["year"]
    y_gz = L.ganzhi_name(L.year_ganzhi_idx(ly))
    w_year = YEAR_WEIGHT.get(y_gz, (0, 5))
    w_month = MONTH_WEIGHT[lm] if lm <= 12 else (0, 5)
    w_day = DAY_WEIGHT[ld] if ld <= 30 else (0, 5)
    hour_branch = ((h + 1) // 2) % 12
    w_hour = HOUR_WEIGHT[hour_branch]

    total_liang = w_year[0] + w_month[0] + w_day[0] + w_hour[0]
    total_qian = w_year[1] + w_month[1] + w_day[1] + w_hour[1]
    total_liang += total_qian // 10
    total_qian %= 10

    parts = {
        "year": {"value": _fmt(w_year), "label": y_gz + "年"},
        "month": {"value": _fmt(w_month), "label": L.LUNAR_MONTH[lm - 1] + "月"},
        "day": {"value": _fmt(w_day), "label": L.LUNAR_DAY[ld - 1]},
        "hour": {"value": _fmt(w_hour), "label": L.EARTHLY[hour_branch] + "时"},
    }
    key = (total_liang, total_qian)
    luck = _luck_level(total_liang)
    song = SONGS.get(key, "骨重未收录，请参考专业命书。")
    return {
        "total": _fmt(key),
        "total_liang": total_liang, "total_qian": total_qian,
        "parts": parts, "song": song, "luck": luck,
        "lunar": {"year": ly, "month": lm, "day": ld},
    }


def _fmt(w: tuple) -> str:
    liang, qian = w
    if qian == 0:
        return f"{liang}两"
    if liang == 0:
        return f"{qian}钱"
    return f"{liang}两{qian}钱"


def _luck_level(liang: int) -> str:
    if liang >= 6:
        return "上上"
    if liang >= 5:
        return "上平"
    if liang >= 4:
        return "中上"
    if liang >= 3:
        return "中平"
    return "下平"